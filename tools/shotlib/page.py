"""Build stage helper: generate <shot>/build/index.html + shot-config.js + manifest.json. The page loads the SHARED renderer
library from /tools/render/ (no per-shot copy of the engine) and only the shot's own scene files from /work/shots/<id>/scene/.
Served from the repo root by tools/record/server.py, so every URL is root-absolute."""
from __future__ import annotations
import json
from pathlib import Path
from .engine import hash_inputs

FONT_FACES = [("thmanyahsans", "Medium", 500), ("thmanyahsans", "Bold", 700), ("thmanyahseriftext", "Bold", 700)]


def config_for(shot: dict, shot_rel: str) -> dict:
    keys = ("id", "fps", "duration_s", "canvas", "character", "world", "catalogue_url", "catalogue", "writing_t0", "cuts", "smears", "fonts", "actors", "draw_order")
    cfg = {k: shot[k] for k in keys + ("format", "calm") if k in shot}   # "calm": the acting data of a calm-format shot (tools/calm.py), read by scene/calm-scene.js   # a multi-actor shot has `actors` (and `draw_order`) instead of `character` / `catalogue` (tools/render/characters/README.md)
    if "actors" not in shot:
        missing = [k for k in keys[:-2] if k not in shot]
        if missing:
            raise KeyError(f"shot.json lacks {missing}")
    cfg["plan_url"] = f"/{shot_rel}/camera-plan.json"
    return cfg


def script_urls(shot: dict, shot_rel: str) -> list[str]:
    urls = []
    for item in shot["library"]:
        if item == "@scene":
            urls += [f"/{shot_rel}/{s}" for s in shot["scene_files"]]
        else:
            urls.append(f"/tools/render/{item}")
    return urls


def write_build(root: Path, shot_dir: Path, shot: dict) -> dict:
    rel = shot_dir.resolve().relative_to(root.resolve()).as_posix()
    b = shot_dir / "build"
    b.mkdir(parents=True, exist_ok=True)
    cfg = config_for(shot, rel)
    (b / "shot-config.js").write_text("// generated by tools/shot.py build; do not edit\nconst SHOT = " + json.dumps(cfg, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    faces = "\n".join(f'@font-face{{font-family:"{fam}";src:url("/assets/fonts/{fam}-{w}.woff2") format("woff2");font-weight:{wt}}}' for fam, w, wt in FONT_FACES)
    scripts = "".join(f'<script src="{u}"></script>' for u in [f"/{rel}/build/shot-config.js"] + script_urls(shot, rel))
    html = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>{shot['id']} renderer</title>
<style>
{faces}
body{{margin:0;background:#222}} canvas{{width:270px;height:480px;display:block}}
</style></head>
<body>
<!-- Recording rig only (served by tools/record/server.py). Previews play the recorded mp4, never this canvas. Generated by tools/shot.py build. -->
<canvas id="shot" width="{shot['canvas'][0]}" height="{shot['canvas'][1]}"></canvas>
{scripts}
<script>document.title = SHOT.id + " renderer";</script>
</body></html>
"""
    (b / "index.html").write_text(html, encoding="utf-8")
    lib_files = [root / "tools" / "render"]
    scene_files = [shot_dir / s for s in shot["scene_files"]]
    urls = script_urls(shot, rel)
    for a in shot.get("actors", []):   # loaded by actors.js at run time (isolated scope), listed so the build stage still runs `node --check` on them
        u = f"/tools/render/characters/{a['module']}.js"
        if u not in urls:
            urls.append(u)
    manifest = {"id": shot["id"], "library": hash_inputs(lib_files, root), "scene": hash_inputs(scene_files, root), "scripts": urls}
    (b / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    return manifest
